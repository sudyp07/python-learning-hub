# f string is needed and used if you want to assign variable values inside the sentence

# ASSIGNING VALUE TO THE RESPECTIVE VARIABLES
first_name = "Sudeep"
age = 23
is_student = True
height = 5.9

## PRINT THE DETAIL IN SENTENCE WITH RESPECTIVE
print(f'My first name is {first_name}.')
print(f'MY AGE  IS {age}.')
print(f"Is he a student ? {is_student}.")
print(f'MY HEIGHT IS {height} Feet.')

## output
"""
My first name is Sudeep.                --> Strings
MY AGE  IS 23.                          --> Integers
Is he a student ? True.                 --> Boolean
MY HEIGHT IS 5.9 Feet.                  --> Float
"""