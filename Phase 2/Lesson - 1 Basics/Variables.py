## there are 4 main types of variables which are
"""
string = alphabets
integer = number
float = decimal number
boolean = true or false
"""

# ---------------------------------------------------
# 1. INTEGER (int)
# Used to store whole numbers.
# ---------------------------------------------------
age = 21
# Print the value
print("Age:", age) ## Age: 21
# Check the data type
print("Type of age:", type(age))  ##Type of age : integer

# ---------------------------------------------------
# 2. FLOAT (float)
# Used to store decimal portion.
# ---------------------------------------------------
height = 5.9
# Print the value
print("Height:", height) ## Height : 5.9
# Check the data type
print("Type of height:", type(height)) ## Type of name: FLOAT

# ---------------------------------------------------
# 3. STRING (str)
# Used to store text inside quotes.
# ---------------------------------------------------
name = "Sudip"
# Print the value
print("Name:", name)   #Sudip
# Check the data type
print("Type of name:", type(name))  ##Type of name: STRING

# ---------------------------------------------------
# 4. BOOLEAN (bool)
# Used to store only True or False.
# ---------------------------------------------------
is_student = True
# Print the value
print("Student:", is_student)  #True
# Check the data type
print("Type of is_student:", type(is_student))  #BOOLEAN

