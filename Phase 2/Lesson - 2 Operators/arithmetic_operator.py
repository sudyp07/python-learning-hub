"""Introduction to Arithmetic Operators"""

"""
Arithmetic operators are used to perform basic mathematical operations on numbers in Python. They work just like the mathematical
operations you use in everyday calculations, such as addition, subtraction, multiplication, and division. Python provides seven
arithmetic operators: +, -, *, /, //, %, and **, each performing a specific mathematical operation and returning a result.
"""

'''
Operator	       Name	               Example	               Result     
+	             Addition	            5 + 3	   -->           8                
-	             Subtraction	        5 - 3	   -->           2                 
*	             Multiplication	        5 * 3	   -->           15                 
/	             Division	            5 / 2	   -->           2.5                 
//	             Floor division	        5 // 2	   -->           2                 
%	             Modulus	            5 % 2	   -->           1                 
**	             Exponentiation	        5 ** 3	   -->           125                  
'''

