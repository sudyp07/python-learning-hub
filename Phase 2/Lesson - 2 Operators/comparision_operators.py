"""Introduction to Comparison Operators"""

"""
Comparison operators are used to compare two values in Python. They check the relationship between two operands and return a
Boolean result, either True or False. These operators are commonly used in decision-making statements such as if, elif, and else
to control the flow of a program. Python provides six comparison operators: ==, !=, >, <, >=, and <=, each used to compare values
in different ways.
"""

'''
Operator        Name                               Example            Result
==              Equal to                    -->    5 == 3      -->     False
!=              Not equal to                -->    5 != 3      -->     True
>               Greater than                -->    5 > 3       -->     True
<               Less than                   -->    5 < 3       -->     False
>=              Greater than or equal to    -->    5 >= 3      -->     True
<=              Less than or equal to       -->    5 <= 3      -->     False
'''