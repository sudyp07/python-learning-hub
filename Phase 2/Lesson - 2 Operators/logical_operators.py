"""Introduction to Logical Operators"""

"""
Logical operators are used to combine multiple conditions and perform logical operations in Python. They are mainly used with
Boolean values (True and False) to make decisions based on multiple expressions. Logical operators help control the flow of a
program by checking whether conditions are true or false. Python provides three logical operators: and, or, and not. The 'and'
operator returns True only when all conditions are True, the 'or' operator returns True when at least one condition is True, and
the 'not' operator reverses the Boolean result.
"""

'''
Operator        Name                          Example                   Result
and             Logical AND                  True and True              True
or              Logical OR                   True or False              True
not             Logical NOT                  not True                   False
not             Logical NOT                  not False                  True
'''