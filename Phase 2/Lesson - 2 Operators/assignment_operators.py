"""Introduction to Assignment Operators"""

"""
Assignment operators are used to assign values to variables or update the existing value of a variable in Python. They combine
the assignment operator (=) with arithmetic operations to make code shorter, cleaner, and easier to understand. Instead of writing
long expressions like x = x + 5, we can use a shorter form like x += 5. Python provides several assignment operators such as
=, +=, -=, *=, /=, //=, %=, and **=, which are commonly used to modify variable values during program execution.
"""

'''
Operator        Name                       best practice        Equivalent         Result
=               Assignment                     x = 5            x = 5               5
+=              Addition Assignment            x += 3           x = x + 3           8
-=              Subtraction Assignment         x -= 2           x = x - 2           6
*=              Multiplication Assignment      x *= 4           x = x * 4           24
/=              Division Assignment            x /= 2           x = x / 2           12.0
//=             Floor Division Assignment      x //= 5          x = x // 5          2.0
%=              Modulus Assignment             x %= 2           x = x % 2           0
**=             Exponent Assignment            x **= 3          x = x ** 3          8
'''