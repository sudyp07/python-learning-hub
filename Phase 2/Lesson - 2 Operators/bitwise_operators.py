"""Introduction to Bitwise Operators"""

"""
Bitwise operators are used to perform operations on numbers at the binary level (bits). They work by comparing and manipulating
the individual bits of integer values. These operators are commonly used in low-level programming, encryption, networking, and
performance optimization tasks. Python provides six main bitwise operators: &, |, ^, ~, <<, and >>. Each operator performs a
specific operation on the binary representation of numbers.
"""

'''
Operator        Name                         Example        Result
&               Bitwise AND                  5 & 3            1
|               Bitwise OR                   5 | 3            7
^               Bitwise XOR                  5 ^ 3            6
~               Bitwise NOT                  ~5              -6
<<              Left Shift                   5 << 1           10
>>              Right Shift                  5 >> 1           2
'''