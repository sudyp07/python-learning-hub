# Weight Conversion: Kilograms (kg) to Pounds (lbs)

# Get the weight in kilograms from the user
weight_kg = float(input("Enter the weight in kilograms (kg): "))

# Convert kilograms to pounds
weight_lbs = weight_kg * 2.20462

# Display the result
print(f"{weight_kg:.2f} kg is equal to {weight_lbs:.2f} lbs.")